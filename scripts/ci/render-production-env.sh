#!/usr/bin/env sh

set -eu

SCRIPT_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
. "$SCRIPT_DIR/common.sh"

require_env APP_KEY APP_URL DB_HOST DB_PORT DB_DATABASE DB_USERNAME DB_PASSWORD MAIL_HOST MAIL_PORT MAIL_USERNAME MAIL_PASSWORD

APP_NAME=${APP_NAME:-Prospera}
APP_ENV=${APP_ENV:-production}
APP_LOCALE=${APP_LOCALE:-en}
APP_FALLBACK_LOCALE=${APP_FALLBACK_LOCALE:-en}
APP_FAKER_LOCALE=${APP_FAKER_LOCALE:-en_US}
APP_MAINTENANCE_DRIVER=${APP_MAINTENANCE_DRIVER:-file}
BCRYPT_ROUNDS=${BCRYPT_ROUNDS:-12}
LOG_CHANNEL=${LOG_CHANNEL:-stack}
LOG_STACK=${LOG_STACK:-single}
LOG_DEPRECATIONS_CHANNEL=${LOG_DEPRECATIONS_CHANNEL:-null}
LOG_LEVEL=${LOG_LEVEL:-warning}
DB_CONNECTION=${DB_CONNECTION:-pgsql}
SESSION_DRIVER=${SESSION_DRIVER:-database}
SESSION_LIFETIME=${SESSION_LIFETIME:-120}
SESSION_ENCRYPT=${SESSION_ENCRYPT:-false}
SESSION_PATH=${SESSION_PATH:-/}
SESSION_DOMAIN=${SESSION_DOMAIN:-null}
BROADCAST_CONNECTION=${BROADCAST_CONNECTION:-log}
FILESYSTEM_DISK=${FILESYSTEM_DISK:-local}
QUEUE_CONNECTION=${QUEUE_CONNECTION:-database}
CACHE_STORE=${CACHE_STORE:-database}
MAIL_MAILER=${MAIL_MAILER:-smtp}
MAIL_SCHEME=${MAIL_SCHEME:-smtps}
MAIL_FROM_ADDRESS=${MAIL_FROM_ADDRESS:-no-reply@prospera.mind2soft.com}
MAIL_FROM_NAME=${MAIL_FROM_NAME:-$APP_NAME}
VITE_APP_NAME=${VITE_APP_NAME:-$APP_NAME}

cat <<EOF
APP_NAME="$APP_NAME"
APP_ENV=$APP_ENV
APP_KEY=$APP_KEY
APP_DEBUG=false
APP_URL=$APP_URL

APP_LOCALE=$APP_LOCALE
APP_FALLBACK_LOCALE=$APP_FALLBACK_LOCALE
APP_FAKER_LOCALE=$APP_FAKER_LOCALE

APP_MAINTENANCE_DRIVER=$APP_MAINTENANCE_DRIVER

BCRYPT_ROUNDS=$BCRYPT_ROUNDS

LOG_CHANNEL=$LOG_CHANNEL
LOG_STACK=$LOG_STACK
LOG_DEPRECATIONS_CHANNEL=$LOG_DEPRECATIONS_CHANNEL
LOG_LEVEL=$LOG_LEVEL

DB_CONNECTION=$DB_CONNECTION
DB_HOST=$DB_HOST
DB_PORT=$DB_PORT
DB_DATABASE=$DB_DATABASE
DB_USERNAME=$DB_USERNAME
DB_PASSWORD=$DB_PASSWORD

SESSION_DRIVER=$SESSION_DRIVER
SESSION_LIFETIME=$SESSION_LIFETIME
SESSION_ENCRYPT=$SESSION_ENCRYPT
SESSION_PATH=$SESSION_PATH
SESSION_DOMAIN=$SESSION_DOMAIN

BROADCAST_CONNECTION=$BROADCAST_CONNECTION
FILESYSTEM_DISK=$FILESYSTEM_DISK
QUEUE_CONNECTION=$QUEUE_CONNECTION

CACHE_STORE=$CACHE_STORE

MAIL_MAILER=$MAIL_MAILER
MAIL_SCHEME=$MAIL_SCHEME
MAIL_HOST=$MAIL_HOST
MAIL_PORT=$MAIL_PORT
MAIL_USERNAME=$MAIL_USERNAME
MAIL_PASSWORD=$MAIL_PASSWORD
MAIL_FROM_ADDRESS=$MAIL_FROM_ADDRESS
MAIL_FROM_NAME="$MAIL_FROM_NAME"

VITE_APP_NAME="$VITE_APP_NAME"
EOF
